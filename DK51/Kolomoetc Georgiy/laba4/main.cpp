#include <GL/glut.h>
#include <iostream>
#include "figure.h"

List figureList;
float globalAngle = 0.0f; // Змінна для зберігання кута обертання

// Функція генерації випадкового числа у заданому діапазоні (для створення різних фігур)
float randomFloat(float min, float max) {
    return min + static_cast<float>(rand()) / (static_cast<float>(RAND_MAX / (max - min)));
}

// Функція для створення випадкового трикутника
Figure createRandomTriangle() {
    Figure f;
    f.p1 = { randomFloat(-0.5f, 0.5f), randomFloat(-0.5f, 0.5f) };
    f.p2 = { randomFloat(-0.5f, 0.5f), randomFloat(-0.5f, 0.5f) };
    f.p3 = { randomFloat(-0.5f, 0.5f), randomFloat(-0.5f, 0.5f) };
    f.r = randomFloat(0.1f, 1.0f);
    f.g = randomFloat(0.1f, 1.0f);
    f.b = randomFloat(0.1f, 1.0f);
    return f;
}

// Функція відмальовки (викликається OpenGL кожен кадр)
void display() {
    // Очищення буфера кольору
    glClear(GL_COLOR_BUFFER_BIT);

    // Збереження поточної матриці
    glPushMatrix();

    // Обертання всієї сцени навколо початку координат (0,0) по осі Z
    glRotatef(globalAngle, 0.0f, 0.0f, 1.0f);

    // Виклик функції малювання всіх фігур зі списку
    drawList(&figureList);

    // Відновлення матриці
    glPopMatrix();

    // Заміна буферів (подвійна буферизація для уникнення мерехтіння)
    glutSwapBuffers();
}

// Функція обробки таймера для створення анімації
void timer(int value) {
    globalAngle += 1.5f; // Збільшення кута обертання (це швидкість обертання)
    if (globalAngle > 360.0f) {
        globalAngle -= 360.0f;
    }

    // Сигнал для OpenGL, що потрібно перемалювати вікно з новими даними
    glutPostRedisplay();

    // Рекурсивний виклик таймера кожні 16 мс (забезпечує ~60 FPS)
    glutTimerFunc(16, timer, 0);
}

// Функція обробки натискань клавіатури (для демонстрації роботи списку: вставка та видалення)
void keyboard(unsigned char key, int x, int y) {
    if (key == 'a' || key == 'A') { // 'a' - додати фігуру
        pushBack(&figureList, createRandomTriangle());
    }
    else if (key == 'd' || key == 'D') { // 'd' - видалити фігуру
        popFront(&figureList);
    }
}

int main(int argc, char** argv) {
    // Ініціалізація списку
    initList(&figureList);

    // Додаємо кілька початкових фігур для демонстрації
    pushBack(&figureList, createRandomTriangle());
    pushBack(&figureList, createRandomTriangle());

    // Базова ініціалізація GLUT
    glutInit(&argc, argv);
    glutInitDisplayMode(GLUT_DOUBLE | GLUT_RGB);
    glutInitWindowSize(800, 600);
    glutCreateWindow("Lab 4: OpenGL + Doubly Linked List");

    // Реєстрація callback-функцій
    glutDisplayFunc(display);
    glutTimerFunc(0, timer, 0);
    glutKeyboardFunc(keyboard); // Реєстрація клавіатури для тестів

    std::cout << "=== Керування ===\n";
    std::cout << "Натиснить 'A' (англ) для додавання фiгури\n";
    std::cout << "Натиснить 'D' (англ) для видалення фiгури\n";

    // Головний цикл програми
    glutMainLoop();
    return 0;
}

